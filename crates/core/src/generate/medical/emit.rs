use super::super::layout::{EXTERIOR, INTERIOR};
use super::super::program::Archetype;
use super::super::report::{Check, Status};
use super::super::{AreaRequest, Built, FILES, GENERATOR_VERSION, MANIFEST, Refusal, fnv1a64, pretty};
