//! A medical day layout as files: the script it compiles to (layout only: walls, doors, room separation lines and rooms), run in a
//! scratch project and read back by the topology extractor; the generated graph, with the net areas BIMCraft measured; the
//! building and the report.

use std::collections::BTreeMap;

use serde_json::{Value, json};

use super::super::graph::{BUILDING_KIND, SCHEMA_VERSION, TOPOLOGY_KIND};
