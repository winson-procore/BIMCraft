pub const RULE_SET: &str = "medical-day-pack/1";
const NAME: &str = "medical-day";

/// The commands of a medical day script, and the room each `room` command makes.
pub struct Script {
    pub lines: Vec<(&'static str, Value)>,
    pub rooms: Vec<(usize, usize)>,
    pub text: String,
}

/// A try that ran: its script, the replies, the generated graph and the checks.
pub struct Done {
    pub script: Script,
    pub replies: Vec<Value>,
    pub graph: Value,
    pub checks: Vec<Check>,
}

fn line(id: &'static str, params: Value) -> (&'static str, Value) {
    (id, params)
}

pub fn compile(c: &Case, l: &Layout, seed: u64, area: AreaRequest) -> Script {
    let title = format!("Medical day {} m2, seed {seed}", area.m2.round());
    let mut lines = vec![
        line("new", json!({"name": title})),
        line("drawing_property", json!({"name": "building_type", "value": Archetype::MedicalDay.building_type()})),
        line("room_area", json!({"at": "finish"})),
        line("level", json!({"elevation": 3600, "name": "Roof"})),
    ];
    for w in &l.walls {
        let kind = if w.exterior { EXTERIOR } else { INTERIOR };
        lines.push(line("wall", json!({"points": [w.a, w.b], "closed": false, "type": kind})));
    }
    lines.push(line("floor", json!({"boundary": l.boundary})));
    // The families the doors are of, with the types they use: one line for each.
    let mut types: BTreeMap<&str, BTreeMap<String, i64>> = BTreeMap::new();
    for d in &l.doors {
        types.entry(d.family).or_default().insert(d.ty.clone(), d.width);
    }
    for (family, set) in &types {
        let set: serde_json::Map<String, Value> = set.iter().map(|(ty, w)| (ty.clone(), json!({"Width": w, "Height": 2100}))).collect();
        lines.push(line("family", json!({"name": family, "types": set})));
    }
    for (i, d) in l.doors.iter().enumerate() {
        let mut params = json!({"at": d.at, "family": d.family, "type": d.ty, "mark": format!("D{}", i + 1)});
        if d.flip_facing {
            params["flip_facing"] = json!(true);
        }
        if d.flip_hand {
            params["flip_hand"] = json!(true);
        }
        lines.push(line("door", params));
    }
    for s in &l.separators {
        lines.push(line("room_separator", json!({"points": s})));
    }
    let mut rooms = Vec::new();
    for (i, r) in c.rooms.iter().enumerate() {
        rooms.push((lines.len(), i));
        lines.push(line("room", json!({"point": l.rects[i].mid(), "name": r.name, "number": r.id})));
    }
    let mut text = format!("# Generated by the BIMCraft graph generator: medical-day, seed {seed}. One command to a line.\n");
    for (id, params) in &lines {
        text.push_str(id);
        text.push(' ');
        text.push_str(&params.to_string());
        text.push('\n');
    }
    Script { lines, rooms, text }
}

fn id_of(c: &Case, i: usize) -> &str {
    &c.rooms[i].id
}

fn pair(a: &str, b: &str) -> (String, String) {
    if a <= b { (a.into(), b.into()) } else { (b.into(), a.into()) }
}

/// The generated graph: its rooms with the net areas measured (by id), its doors and its open links. No entry.
fn graph_json(c: &Case, l: &Layout, seed: u64, areas: &BTreeMap<String, f64>) -> Value {
    let nodes: Vec<Value> = c
        .rooms
        .iter()
        .map(|r| {
            json!({"id": r.id, "kind": r.kind.name(), "role": r.kind.role(), "name": r.name, "area_m2": areas.get(&r.id).copied().unwrap_or(0.0), "level": "Level 1"})
        })
        .collect();
    let mut edges = Vec::new();
    for d in &l.doors {
        let Some(k) = d.link else { continue };
        let link = &c.links[k];
        let (a, b) = (id_of(c, link.a), id_of(c, link.b));
        let mut edge = json!({
            "id": format!("door:{a}:{b}"), "from": a, "to": b, "kind": "door", "operation": d.op, "family": d.family, "type": d.ty,
            "width_mm": d.width,
        });
        if let (Some(o), Some(h)) = (&d.opens_into, d.hinge) {
            edge["opens_into"] = json!(o);
            edge["hinge"] = json!(h);
        }
        edges.push(edge);
    }
    for link in c.links.iter().filter(|l| l.means == Means::Open) {
        let (a, b) = (id_of(c, link.a), id_of(c, link.b));
        edges.push(json!({"id": format!("open:{a}:{b}"), "from": a, "to": b, "kind": "open"}));
    }
    json!({
        "schema_version": SCHEMA_VERSION,
        "graph_kind": TOPOLOGY_KIND,
        "archetype": NAME,
        "seed": seed,
        "entry": Value::Null,
        "nodes": nodes,
        "edges": edges,
    })
}

type Key = ((String, String), String, i64, Option<String>, Option<String>);

/// What the extracted graph says of the generated one: nothing, when they are the same.
pub fn compare(c: &Case, l: &Layout, extracted: &Value) -> Result<(), String> {
    let mut problems = Vec::new();
    let ids: Vec<&str> = extracted["nodes"].as_array().into_iter().flatten().filter_map(|n| n["id"].as_str()).collect();
    for r in &c.rooms {
        if ids.iter().filter(|i| **i == r.id).count() != 1 {
            problems.push(format!("the room `{}` is not made once", r.id));
        }
    }
    if ids.len() != c.rooms.len() {
        problems.push(format!("{} rooms for {}", ids.len(), c.rooms.len()));
    }
    let mut want: BTreeMap<Key, i64> = BTreeMap::new();
    for d in &l.doors {
        let (oi, hg) = (d.opens_into.clone(), d.hinge.map(String::from));
        if let Some(k) = d.link {
            let (a, b) = (id_of(c, c.links[k].a), id_of(c, c.links[k].b));
            *want.entry((pair(a, b), d.op.to_string(), d.width, oi, hg)).or_default() += 1;
        }
    }
    let mut want_open: Vec<(String, String)> =
        c.links.iter().filter(|l| l.means == Means::Open).map(|l| pair(id_of(c, l.a), id_of(c, l.b))).collect();
    want_open.sort();
    let mut got: BTreeMap<Key, i64> = BTreeMap::new();
    let mut got_open: Vec<(String, String)> = Vec::new();
    for e in extracted["edges"].as_array().into_iter().flatten() {
        let (a, b) = (e["from"].as_str().unwrap_or_default(), e["to"].as_str().unwrap_or_default());
        let (oi, hg) = (e["opens_into"].as_str().map(String::from), e["hinge"].as_str().map(String::from));
        let op = e["operation"].as_str().unwrap_or("?").to_string();
        let w = e["width_mm"].as_f64().map_or(-1, |w| w.round() as i64);
        match e["kind"].as_str() {
            Some("door") if e["exterior"] == true => problems.push(format!("a door from `{a}` to the outside")),
            Some("door") => *got.entry((pair(a, b), op, w, oi, hg)).or_default() += 1,
            Some("open") => got_open.push(pair(a, b)),
            _ => {}
        }
    }
    got_open.sort();
    if want != got {
        let show = |k: &Key| format!("{} to {} by {} {} opening into {:?}, hinge {:?}", k.0.0, k.0.1, k.1, k.2, k.3, k.4);
        let missing: Vec<_> = want.iter().filter(|(k, n)| got.get(*k) != Some(n)).map(|(k, _)| show(k)).collect();
        let extra: Vec<_> = got.iter().filter(|(k, n)| want.get(*k) != Some(n)).map(|(k, _)| show(k)).collect();
        problems.push(format!("doors: missing {missing:?}, extra {extra:?}"));
    }
    if want_open != got_open {
        problems.push(format!("open links: wanted {want_open:?}, extracted {got_open:?}"));
    }
    if extracted["exterior_doors"].as_array().is_some_and(|d| !d.is_empty()) {
        problems.push("the plan has an exterior door".into());
    }
    if !extracted["entry"].is_null() {
        problems.push(format!("the entry is {}, not null", extracted["entry"]));
    }
    if extracted["diagnostics"].as_array().is_some_and(|d| !d.is_empty()) {
        problems.push(format!("diagnostics {}", extracted["diagnostics"]));
    }
    if problems.is_empty() { Ok(()) } else { Err(problems.join("; ")) }
}

fn rules_pass(graph: &Value) -> Result<Vec<Value>, String> {
    let pack = Pack::embedded(NAME)?;
    let g = RuleGraph::from_value(graph)?;
    let results = graph_rules::check(pack, &g)?;
    let failed: Vec<String> =
        results.iter().filter(|c| c.status == graph_rules::Status::Fail).map(|c| format!("{} {}: {}", c.id, c.name, c.detail)).collect();
    if failed.is_empty() { Ok(results.iter().map(graph_rules::Check::json).collect()) } else { Err(failed.join("; ")) }
}

/// Builds the layout in a scratch project and reads it back: its graph is what was generated, or why not.
pub fn verify(c: &Case, l: &Layout, seed: u64, area: AreaRequest) -> Result<Done, String> {
    let deviation = (l.gross_mm2 as f64 / 1.0e6 - area.m2).abs() / area.m2;
    if deviation > 0.05 {
        return Err(format!("the plan is {:.1} m2 gross for {} m2 asked", l.gross_mm2 as f64 / 1.0e6, area.m2));
    }
    let script = compile(c, l, seed, area);
    let mut scratch = Session::new();
    let replies = scratch.script(&script.text).map_err(|e| format!("the script does not run: {e}"))?;
    for (at, room) in &script.rooms {
        if let Some(w) = replies.get(*at).and_then(|r| r.get("warning")).and_then(Value::as_str) {
            return Err(format!("the room `{}` is not bounded: {w}", c.rooms[*room].id));
        }
    }
    let extracted = crate::topology::extract(&scratch.model);
    compare(c, l, &extracted)?;
    let areas: BTreeMap<String, f64> = extracted["nodes"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|n| Some((n["id"].as_str()?.to_string(), n["area_m2"].as_f64()?)))
        .collect();
    let graph = graph_json(c, l, seed, &areas);
    let generated = rules_pass(&graph).map_err(|e| format!("the generated graph fails the medical-day rules: {e}"))?;
    let mut built = extracted.clone();
    let kinds: BTreeMap<&str, &str> = c.rooms.iter().map(|r| (r.id.as_str(), r.kind.name())).collect();
    if let Some(nodes) = built["nodes"].as_array_mut() {
        for n in nodes {
            let kind = n["id"].as_str().and_then(|i| kinds.get(i)).copied();
            n["kind"] = json!(kind);
        }
    }
    built["archetype"] = json!(NAME);
    rules_pass(&built).map_err(|e| format!("the built medical day plan fails the medical-day rules: {e}"))?;
    let checks = vec![
        Check {
            id: "MDG-001",
            name: "graph-passes-medical-day-pack",
            status: Status::Pass,
            detail: format!("{} rules pass on the generated graph", generated.len()),
        },
        Check {
            id: "MDG-002",
            name: "script-runs",
            status: Status::Pass,
            detail: format!("all {} commands ran in a fresh project", script.lines.len()),
        },
        Check {
            id: "MDG-003",
            name: "extracted-equals-generated",
            status: Status::Pass,
            detail: "the topology extractor finds the generated rooms, doors and open links, no entry and no diagnostics".into(),
        },
        Check {
            id: "MDG-004",
            name: "built-passes-medical-day-pack",
            status: Status::Pass,
            detail: "the extracted graph, with the generated kinds, passes the medical-day rules".into(),
        },
        Check {
            id: "MDG-005",
            name: "area-fidelity",
            status: if deviation <= 0.06 { Status::Pass } else { Status::Warn },
            detail: format!("{:.2} m2 gross for {} m2 asked", l.gross_mm2 as f64 / 1.0e6, area.m2),
        },
    ];
    Ok(Done { script, replies, graph, checks })
}

fn program_json(c: &Case, seed: u64, area: AreaRequest) -> Value {
    let pack = Pack::embedded(NAME).ok();
    json!({
        "schema_version": SCHEMA_VERSION,
        "archetype": NAME,
        "seed": seed,
        "requested_area_m2": area.m2,
        "pack_id": pack.map(|p| p.pack_id.clone()),
        "spaces": c.rooms.iter().map(|r| json!({"id": r.id, "kind": r.kind.name(), "label": r.name, "role": r.kind.role()})).collect::<Vec<_>>(),
        "edges": c.links.iter().map(|l| json!({
            "from": id_of(c, l.a), "to": id_of(c, l.b), "kind": if l.means == Means::Open { "open" } else { "door" },
            "means": match l.means { Means::Open => "open", Means::Single(_) => "swing", Means::Pair => "double-swing" },
        })).collect::<Vec<_>>(),
        "entry": Value::Null,
    })
}

fn building_json(c: &Case, l: &Layout, seed: u64, topology_hash: &str, edges: usize) -> Value {
    let bounds = |r: &Rect| json!({"x0": r.x0, "y0": r.y0, "x1": r.x1, "y1": r.y1});
    let door_edge = |d: &DoorAt| {
        d.link.map_or(Value::Null, |k| json!(format!("door:{}:{}", id_of(c, c.links[k].a), id_of(c, c.links[k].b))))
    };
    json!({
        "schema_version": SCHEMA_VERSION,
        "graph_kind": BUILDING_KIND,
        "archetype": NAME,
        "seed": seed,
        "units": "mm",
        "source_2d": {"file": "topology-graph.json", "topology_hash": topology_hash, "nodes": c.rooms.len(), "edges": edges},
        "footprint": {"width": l.width, "depth": l.depth, "boundary": l.boundary},
        "levels": [{"id": "level_1", "name": "Level 1", "elevation_mm": 0}, {"id": "level_roof", "name": "Roof", "elevation_mm": 3600}],
        "spaces": c.rooms.iter().enumerate().map(|(i, r)| json!({"id": format!("space_{}", r.id), "source_2d": r.id, "level": "level_1", "bounds": bounds(&l.rects[i])})).collect::<Vec<_>>(),
        "walls": l.walls.iter().enumerate().map(|(i, w)| json!({
            "id": format!("wall_{}", i + 1), "kind": if w.exterior { "exterior" } else { "partition" },
            "type": if w.exterior { EXTERIOR } else { INTERIOR }, "start": w.a, "end": w.b,
        })).collect::<Vec<_>>(),
        "separators": l.separators.iter().enumerate().map(|(i, s)| json!({"id": format!("separator_{}", i + 1), "start": s[0], "end": s[1]})).collect::<Vec<_>>(),
        "openings": l.doors.iter().enumerate().map(|(i, d)| json!({
            "id": format!("door_{}", i + 1), "kind": "door", "at": d.at, "family": d.family, "type": d.ty, "operation": d.op,
            "width_mm": d.width, "source_2d": id_of(c, d.rooms.0), "source_topology_edge": door_edge(d),
        })).collect::<Vec<_>>(),
        "slabs": [{"id": "slab_level_1", "kind": "floor", "level": "level_1", "boundary": l.boundary}],
        "vertical_circulation": [],
        "components": [],
        "systems": [],
    })
}

/// The run directory's files.
pub fn finish(c: &Case, l: &Layout, done: Done, seed: u64, area: AreaRequest) -> Result<Built, Refusal> {
    let topology_text = pretty(&done.graph)?;
    let topology_hash = fnv1a64(&topology_text);
    let edges = done.graph["edges"].as_array().map_or(0, Vec::len);
    let measured: Vec<Value> = done
        .script
        .rooms
        .iter()
        .filter_map(|(at, room)| Some(json!({"space": c.rooms[*room].id, "net_area_m2": done.replies.get(*at)?.get("area_m2")?})))
        .collect();
    let net: f64 = measured.iter().filter_map(|m| m["net_area_m2"].as_f64()).sum();
    let gross = l.gross_mm2 as f64 / 1.0e6;
    let count = |s: Status| done.checks.iter().filter(|c| c.status == s).count();
    let f = &c.flags;
    let plan = json!({
        "service": f.service,
        "office_band": f.office_band,
        "blocks": f.blocks,
        "head_row": f.head_row,
        "second_end_corridor": f.second_end,
        "quarter_turns": l.quarters,
        "mirror": l.mirror,
        "shear": 0,
    });
    let report = json!({
        "schema_version": SCHEMA_VERSION,
        "archetype": NAME,
        "seed": seed,
        "plan": plan,
        "rule_set": RULE_SET,
        "summary": {"pass": count(Status::Pass), "warn": count(Status::Warn), "fail": count(Status::Fail)},
        "checks": done.checks.iter().map(|c| json!({"id": c.id, "name": c.name, "status": match c.status { Status::Pass => "PASS", Status::Warn => "WARN", Status::Fail => "FAIL" }, "detail": c.detail})).collect::<Vec<_>>(),
        "warnings": done.checks.iter().filter(|c| c.status == Status::Warn).map(|c| format!("{}: {}", c.id, c.detail)).collect::<Vec<_>>(),
        "rules": rules_pass(&done.graph).unwrap_or_default(),
        "capability_notes": [
            "The plan is the pattern of specs/medical-day-pattern-generator.md: a window band of treatment bays, a patient corridor, core blocks between cross corridors, an optional office band and a staff corridor; the topology extractor, run on the built project, gives the generated graph, which the medical-day pack (`data/graph-rules/medical-day.json`) judges.",
            "Areas in the building file are gross, to wall centre lines; the topology graph's `area_m2` and `measured_rooms` are the net areas BIMCraft computed for each room.",
            "A department, not a building: no exterior door and no entry. Layout only: walls, doors of the Single Door and Double Door families, room separation lines and rooms. No windows, grids, dimensions, text, fixtures or furniture. Turned and mirrored by the seed, never sheared.",
        ],
        "scores": {"room_count": c.rooms.len(), "net_to_gross": if gross > 0.0 { (net / gross * 1000.0).round() / 1000.0 } else { 0.0 }},
        "measured_rooms": measured,
    });
    let texts = [
        pretty(&program_json(c, seed, area))?,
        topology_text,
        pretty(&building_json(c, l, seed, &topology_hash, edges))?,
        done.script.text.clone(),
        pretty(&report)?,
    ];
    let named: Vec<Value> =
        FILES.iter().zip(&texts).map(|((key, name), text)| json!({"key": key, "path": name, "hash": fnv1a64(text)})).collect();
    let manifest = pretty(&json!({
        "schema_version": SCHEMA_VERSION,
        "generator_version": GENERATOR_VERSION,
        "archetype": NAME,
        "seed": seed,
        "service": f.service,
        "office_band": f.office_band,
        "blocks": f.blocks,
        "head_row": f.head_row,
        "second_end_corridor": f.second_end,
        "quarter_turns": l.quarters,
        "mirror": l.mirror,
        "shear": 0,
        "requested_area": {"value": area.value, "unit": area.unit},
        "requested_area_m2": area.m2,
        "gross_area_m2": gross,
        "hash_algorithm": "fnv1a64",
        "topology_hash": topology_hash,
        "files": named,
    }))?;
    let mut files: Vec<(&'static str, String)> = FILES.iter().map(|(_, name)| *name).zip(texts).collect();
    files.push((MANIFEST, manifest));
    Ok(Built {
        archetype: Archetype::MedicalDay,
        seed,
        plan: None,
        checks: done.checks,
        files,
        topology_hash,
        gross_m2: gross,
        rooms: c.rooms.len(),
    })
}
